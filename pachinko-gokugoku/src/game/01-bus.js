// =====================================================================
//  イベントバス（モジュール間の疎結合）
// =====================================================================
const Bus = {
  h: {},
  on(e, f) { (this.h[e] || (this.h[e] = [])).push(f); },
  emit(e, a, b) { const l = this.h[e]; if (l) for (let i = 0; i < l.length; i++) l[i](a, b); }
};
